"""Build-time Chinese glyph atlas, rendered at native resolution. No OS font dependency."""
from pathlib import Path
import cairo
import gi
gi.require_version('Pango','1.0')
gi.require_version('PangoCairo','1.0')
from gi.repository import Pango,PangoCairo

ROOT=Path(__file__).parent
texts=['低电量保护测试','电量不足，请连接充电器','充电保护中，Linux 尚未启动',
       '当前电量：55%','电池电压：3.80 V','电池读数异常，请连接充电器',
       '电量达到15%后，短按电源键启动','音量下键：进入 Fastboot']
font=Pango.FontDescription('Noto Sans CJK SC Medium')
font.set_absolute_size(64*Pango.SCALE)
glyphs={}
runs=[]; records=[]
for char in sorted(set(''.join(texts)+'0123456789.% V')):
    surface=cairo.ImageSurface(cairo.FORMAT_A8,100,100)
    cr=cairo.Context(surface)
    layout=PangoCairo.create_layout(cr);layout.set_font_description(font);layout.set_text(char,-1)
    width,height=layout.get_pixel_size()
    width=max(1,width);height=min(100,height)
    cr.set_source_rgba(1,1,1,1);PangoCairo.show_layout(cr,layout);surface.flush()
    raw=surface.get_data();stride=surface.get_stride()
    levels=[min(15,(raw[y*stride+x]+8)//17) for y in range(height) for x in range(width)]
    offset=len(runs);prev=levels[0];count=0
    for level in levels:
        if level==prev and count<4096:count+=1
        else:
            runs.append((prev<<12)|(count-1));prev,count=level,1
    runs.append((prev<<12)|(count-1))
    records.append((ord(char),width,height,offset,len(runs)-offset))
    glyphs[char]=(surface,width,height)
header=['/* Generated by generate_charge_glyphs.py; 4-bit alpha RLE. */',
        '#include <stdint.h>',
        'struct charge_glyph { uint32_t code; uint16_t width,height; uint32_t offset; uint16_t runs; };',
        'static const uint16_t charge_runs[] = {']
header+=[' '+','.join('0x%04x'%v for v in runs[i:i+16])+',' for i in range(0,len(runs),16)]
header+=['};','static const struct charge_glyph charge_glyphs[] = {']
header+=[' {%d,%d,%d,%d,%d},'%row for row in records]
header+=['};']
(ROOT/'mi4_charge_glyphs.h').write_text('\n'.join(header)+'\n')

# Native landscape preview uses the very same glyph masks and pixel positions.
preview=cairo.ImageSurface(cairo.FORMAT_RGB24,1920,1080)
cr=cairo.Context(preview);cr.set_source_rgb(.02,.03,.045);cr.paint()
for text,y,color in [(texts[0],150,(.98,.55,.35)),(texts[2],280,(.8,.85,.9)),
                     (texts[3],440,(.35,.85,.95)),(texts[4],570,(.85,.9,.95)),
                     (texts[6],770,(.8,.85,.9)),(texts[7],900,(.6,.65,.72))]:
    x=(1920-sum(glyphs[c][1] for c in text))//2
    cr.set_source_rgb(*color)
    for char in text:
        surface,w,h=glyphs[char];cr.mask_surface(surface,x,y);x+=w
preview.write_to_png(str(ROOT/'charge-ui-landscape-preview.png'))
print('GLYPHS',len(records),'RLE_BYTES',len(runs)*2,'FONT_PIXELS',64)
