#!/usr/bin/env python3
"""Mi4 BLE ELM UART bridge prototype; off by default, no synthetic vehicle data.

--advertise-only tests Sky discovery/CCCD/writes without an OBD adapter.
--simulate supplies explicit bench-only changing values, never opens an upstream.
--upstream MAC forwards raw UART, requires kiosk stopped to ensure exclusivity.
No adapter AT configuration is generated by the phone itself.
"""
import argparse
import asyncio
import json
import os
import pty
import re
import signal
import subprocess
import time
from elm_bridge_core import ByteRelay, chunks

ROOT = '/com/mi4/elmbridge'
SERVICE = ROOT+'/service0'
TX = SERVICE+'/char0'
RX = SERVICE+'/char1'
ADV = ROOT+'/advertisement0'
_traffic = {}


def log(event, **fields):
    if event in ('sky_write','forward_to_obd','forward_to_sky') and not fields.get('at'):
        item = _traffic.setdefault(event, [0,0,0.0])
        item[0] += 1
        item[1] += fields.get('bytes',fields.get('size',0))
        if time.monotonic()-item[2] < 5:
            return
        fields.update(packets=item[0], total_bytes=item[1])
        item[2] = time.monotonic()
    print(json.dumps(dict(event=event, monotonic=time.monotonic(), **fields)), flush=True)


def management_command(arguments):
    # btmgmt exits on stdin EOF before its asynchronous completion callback
    # when launched from a systemd service with /dev/null as stdin.
    master, slave = pty.openpty()
    try:
        return subprocess.run(['timeout', '3', 'stdbuf', '-oL', 'btmgmt']+arguments,
                              stdin=slave, capture_output=True, text=True, timeout=7)
    finally:
        os.close(slave)
        os.close(master)


def gatt_types(relay, sky_address):
    from dbus_fast.service import ServiceInterface, method, dbus_property
    from dbus_fast.constants import PropertyAccess
    from dbus_fast import Variant, DBusError
    expected = '/org/bluez/hci0/dev_'+sky_address.replace(':', '_').upper()

    class Service(ServiceInterface):
        def __init__(self):
            super().__init__('org.bluez.GattService1')

        @dbus_property(access=PropertyAccess.READ)
        def UUID(self) -> 's':
            return '0000fff0-0000-1000-8000-00805f9b34fb'

        @dbus_property(access=PropertyAccess.READ)
        def Primary(self) -> 'b':
            return True

        def props(self):
            return {'UUID': Variant('s', self.UUID), 'Primary': Variant('b', True)}

    class Characteristic(ServiceInterface):
        def __init__(self, write):
            super().__init__('org.bluez.GattCharacteristic1')
            self.write = write
            self.last = b''

        @dbus_property(access=PropertyAccess.READ)
        def UUID(self) -> 's':
            return '0000fff%s-0000-1000-8000-00805f9b34fb' % ('1' if self.write else '2')

        @dbus_property(access=PropertyAccess.READ)
        def Service(self) -> 'o':
            return SERVICE

        @dbus_property(access=PropertyAccess.READ)
        def Flags(self) -> 'as':
            return ['write', 'write-without-response'] if self.write else ['notify']

        @dbus_property(access=PropertyAccess.READ)
        def Value(self) -> 'ay':
            return self.last

        @dbus_property(access=PropertyAccess.READ)
        def Notifying(self) -> 'b':
            return relay.notifying if not self.write else False

        @method()
        def WriteValue(self, value: 'ay', options: 'a{sv}'):
            if not self.write:
                raise DBusError('org.bluez.Error.NotPermitted', 'not writable')
            peer = getattr(options.get('device'), 'value', None)
            if peer != expected:
                raise DBusError('org.bluez.Error.NotAuthorized', 'selected SkyGauge only')
            log('sky_write', size=len(value), upstream_ready=relay.ready,
                # Initialization commands only; do not log VIN/ECU replies.
                at=bytes(value).decode('ascii', errors='replace')[:64]
                   if bytes(value).upper().startswith(b'AT') else None)
            try:
                relay.write(value)
            except (RuntimeError, BufferError, ValueError) as exc:
                if isinstance(exc, BufferError) and hasattr(relay, 'end_session'):
                    relay.end_session()
                raise DBusError('org.bluez.Error.Failed', str(exc))

        @method()
        def StartNotify(self):
            if self.write:
                raise DBusError('org.bluez.Error.NotSupported', 'TX does not notify')
            if relay.notifying:
                raise DBusError('org.bluez.Error.InProgress', 'already subscribed')
            relay.clear()
            relay.notifying = True
            if hasattr(relay, 'subscribed'):
                relay.subscribed()
            self.emit_properties_changed({'Notifying': True})
            log('sky_subscribed')

        @method()
        def StopNotify(self):
            if not self.write:
                if hasattr(relay, 'end_session'):
                    relay.end_session()
                relay.notifying = False
                relay.clear()
                self.last = b''
                self.emit_properties_changed({'Notifying': False, 'Value': b''})
                log('sky_unsubscribed')

        def props(self):
            return {'UUID': Variant('s', self.UUID), 'Service': Variant('o', SERVICE),
                    'Flags': Variant('as', self.Flags), 'Value': Variant('ay', b''),
                    'Notifying': Variant('b', self.Notifying)}

    service, tx, rx = Service(), Characteristic(True), Characteristic(False)

    class Application(ServiceInterface):
        def __init__(self):
            super().__init__('org.freedesktop.DBus.ObjectManager')

        @method()
        def GetManagedObjects(self) -> 'a{oa{sa{sv}}}':
            return {SERVICE: {service.name: service.props()}, TX: {tx.name: tx.props()},
                    RX: {rx.name: rx.props()}}

    class Advertisement(ServiceInterface):
        def __init__(self):
            super().__init__('org.bluez.LEAdvertisement1')

        @dbus_property(access=PropertyAccess.READ)
        def Type(self) -> 's':
            return 'peripheral'

        @dbus_property(access=PropertyAccess.READ)
        def ServiceUUIDs(self) -> 'as':
            return [service.UUID]

        @dbus_property(access=PropertyAccess.READ)
        def LocalName(self) -> 's':
            return 'OBDII Mi4'

        @dbus_property(access=PropertyAccess.READ)
        def MinInterval(self) -> 'u':
            return 100

        @dbus_property(access=PropertyAccess.READ)
        def MaxInterval(self) -> 'u':
            return 150

        @dbus_property(access=PropertyAccess.READ)
        def Discoverable(self) -> 'b':
            # A registered peripheral is not necessarily discoverable while
            # Adapter1.Discoverable is false. Match real OBD advertisers.
            return True

        @method()
        def Release(self):
            log('advertisement_released')

    return [(ROOT, Application()), (SERVICE, service), (TX, tx), (RX, rx),
            (ADV, Advertisement())], rx


async def run(args):
    from dbus_fast.aio import MessageBus
    from dbus_fast import BusType, Message, MessageType
    if getattr(args, 'ipc', False):
        from elm_bridge_ipc import GatewayRelay
        relay = GatewayRelay(log)
    else:
        relay = ByteRelay()
    stopped = asyncio.Event()
    loop = asyncio.get_running_loop()
    for sig in (signal.SIGINT, signal.SIGTERM):
        loop.add_signal_handler(sig, stopped.set)
    if args.upstream:
        # The prototype never lets the kiosk issue competing ELM requests.
        result = subprocess.run(['systemctl', 'is-active', '--quiet', 'obd-gauge-kiosk'], check=False)
        if result.returncode == 0:
            raise RuntimeError('kiosk BLE worker active; upstream relay refuses concurrent polling')
    bus = await MessageBus(bus_type=BusType.SYSTEM).connect()
    exports, rx = gatt_types(relay, args.sky_address)
    for path, obj in exports:
        bus.export(path, obj)
    async def call(path, interface, member, signature='', body=None):
        reply = await asyncio.wait_for(bus.call(Message(destination='org.bluez', path=path,
                interface=interface, member=member, signature=signature, body=body or [])), 12)
        if reply.message_type == MessageType.ERROR:
            raise RuntimeError('%s: %s' % (reply.error_name, reply.body))
    client, protocol, tasks = None, None, []
    application_registered = advertised = subscribed = legacy_advertised = False
    failure = asyncio.Event()
    async def tx_worker():
        while True:
            payload = await relay.take_tx()
            if getattr(args, 'ipc', False):
                try:
                    await relay.send(payload)
                except (ConnectionError, OSError, asyncio.TimeoutError):
                    relay.end_session()
                    continue
            else:
                for part in chunks(payload):
                    await client.write_gatt_char(protocol.tx, part, response=protocol.response)
            log('forward_to_obd', bytes=len(payload))
    async def rx_worker():
        while True:
            payload = await relay.take_rx()
            generation = getattr(relay, 'generation', 0)
            for part in chunks(payload):
                if not relay.notifying or generation != getattr(relay, 'generation', 0):
                    break
                rx.last = part
                rx.emit_properties_changed({'Value': part})
                await asyncio.sleep(0)  # yield to D-Bus without a fixed per-chunk delay
            log('forward_to_sky', bytes=len(payload))
    async def demo_worker():
        from elm327_demo import Elm327Demo
        simulator = Elm327Demo()
        previous = -100
        while True:
            payload = await relay.take_tx()
            for reply in simulator.feed(payload):
                relay.receive(reply)
            if time.monotonic()-previous >= 3:
                log('SIMULATED_VALUES_NOT_REAL', **simulator.values())
                previous = time.monotonic()
    def notify(_sender, data):
        try:
            relay.receive(data)
        except Exception as exc:
            log('relay_failed', reason=str(exc))
            failure.set()
    def task_done(task):
        if not task.cancelled() and task.exception():
            log('relay_failed', reason=str(task.exception()))
            failure.set()
    async def monitor_ipc():
        while True:
            if relay.disconnect_requested:
                relay.disconnect_requested = False
                try:
                    await call('/org/bluez/hci0/dev_'+args.sky_address.replace(':','_').upper(),
                               'org.bluez.Device1', 'Disconnect')
                except Exception:
                    pass
                rx.last = b''
                rx.emit_properties_changed({'Value': b'', 'Notifying': False})
            await asyncio.sleep(.1)
    try:
        if getattr(args, 'ipc', False):
            from elm_radio import maintain_low_latency
            await relay.start()
            tasks = [asyncio.create_task(fn()) for fn in (tx_worker, rx_worker, monitor_ipc)]
            tasks.append(asyncio.create_task(maintain_low_latency(relay,args.sky_address,log)))
            for task in tasks:
                task.add_done_callback(task_done)
        if args.simulate:
            relay.ready = True
            tasks = [asyncio.create_task(demo_worker()), asyncio.create_task(rx_worker())]
            for task in tasks:
                task.add_done_callback(task_done)
        if args.upstream:
            from bleak import BleakClient
            from gauge_ble_protocol import select_protocol
            client = BleakClient(args.upstream, timeout=25,
                                 disconnected_callback=lambda _: failure.set())
            await client.connect()
            protocol = select_protocol(client.services)
            if protocol.kind != 'elm':
                raise RuntimeError('upstream is not an ELM UART')
            await client.start_notify(protocol.rx, notify)
            subscribed = True
            relay.ready = True
            tasks = [asyncio.create_task(tx_worker()), asyncio.create_task(rx_worker())]
            for task in tasks:
                task.add_done_callback(task_done)
        await call('/org/bluez/hci0', 'org.bluez.GattManager1', 'RegisterApplication', 'oa{sv}', [ROOT, {}])
        application_registered = True
        if getattr(args, 'ipc', False):
            # An old connection may retain CCCD/handles across app re-registration.
            # Force this specific Sky peer to rediscover the fresh local service.
            try:
                await call('/org/bluez/hci0/dev_'+args.sky_address.replace(':','_').upper(),
                           'org.bluez.Device1', 'Disconnect')
                log('sky_link_reset_after_gatt_registration')
            except Exception:
                pass
        if args.legacy_advertising:
            # BlueZ 5.72 reserves AD type 09 in its D-Bus Data property and
            # always puts LocalName in scan response. MGMT permits a complete
            # legacy ADV payload; instance 2 is bounded by the kernel timeout.
            payload = '0303f0ff0a094f42444949204d6934'
            result = management_command(['add-adv', '-c', '-g', '-d', payload,
                                         '-t', str(args.seconds), '2'])
            if 'Instance added' not in result.stdout:
                raise RuntimeError('legacy advertising failed: '+result.stdout+result.stderr)
            legacy_advertised = True
            log('legacy_main_packet_name_enabled', result=result.stdout.strip())
        else:
            await call('/org/bluez/hci0', 'org.bluez.LEAdvertisingManager1', 'RegisterAdvertisement', 'oa{sv}', [ADV, {}])
            advertised = True
        log('bridge_advertising', name='OBDII Mi4', upstream_ready=relay.ready,
            mode='SIMULATED_BENCH_ONLY' if args.simulate else
                 'gauge_owned_uart_gateway' if getattr(args,'ipc',False) else
                 'real_uart_relay' if args.upstream else 'discovery_only_no_fake_replies')
        stop_task, fail_task = asyncio.create_task(stopped.wait()), asyncio.create_task(failure.wait())
        tasks.extend([stop_task, fail_task])
        await asyncio.wait([stop_task, fail_task], timeout=args.seconds or None, return_when=asyncio.FIRST_COMPLETED)
        if failure.is_set():
            raise RuntimeError('upstream/relay lost; withdraw advertisement instead of serving stale data')
    finally:
        relay.ready = False
        if getattr(args, 'ipc', False):
            await relay.close()
        if legacy_advertised:
            result = management_command(['rm-adv', '2'])
            log('legacy_advertisement_removed', result=result.stdout.strip())
        if advertised:
            try:
                await call('/org/bluez/hci0', 'org.bluez.LEAdvertisingManager1', 'UnregisterAdvertisement', 'o', [ADV])
            except Exception:
                pass
        for task in tasks:
            task.cancel()
        await asyncio.gather(*tasks, return_exceptions=True)
        if client and client.is_connected:
            if subscribed:
                await client.stop_notify(protocol.rx)
            await client.disconnect()
        if application_registered:
            try:
                await call('/org/bluez/hci0', 'org.bluez.GattManager1', 'UnregisterApplication', 'o', [ROOT])
            except Exception:
                pass
        relay.clear()
        bus.disconnect()
        log('bridge_stopped')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument('--advertise-only', action='store_true')
    modes.add_argument('--simulate', action='store_true')
    modes.add_argument('--upstream')
    modes.add_argument('--ipc', action='store_true', help='gauge-owned real uplink through local socket')
    parser.add_argument('--sky-address', required=True)
    parser.add_argument('--seconds', type=int, default=180, help='0: daemon until explicitly stopped')
    parser.add_argument('--legacy-advertising', action='store_true')
    args = parser.parse_args()
    for address in (args.sky_address, args.upstream):
        if address and not re.fullmatch(r'(?:[0-9a-fA-F]{2}:){5}[0-9a-fA-F]{2}', address):
            parser.error('invalid BLE address')
    if not 0 <= args.seconds <= 3600:
        parser.error('duration must be 0 (daemon) or 1..3600 seconds')
    asyncio.run(run(args))


if __name__ == '__main__':
    main()
